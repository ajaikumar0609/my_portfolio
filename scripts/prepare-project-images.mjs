// Usage: node scripts/prepare-project-images.mjs
// Reads the REAL originals in assets/originals/ (git-ignored: they contain client data), pixelates the
// personal-data regions listed in scripts/project-assets.mjs, and writes web-ready WebP into public/.
// Also regenerates src/data/screenshots.ts. Originals are never modified.
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import { SCREENSHOTS, LOGOS } from './project-assets.mjs'

const require = createRequire(import.meta.url)
const sharp = require('sharp')
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const SCALE = 2940 / 2000
const CELL = 14
const result = {}

async function pixelate(buf, regions, width, height) {
  const layers = []
  for (const [x1, y1, x2, y2] of regions) {
    const left = Math.max(0, Math.round(x1 * SCALE))
    const top = Math.max(0, Math.round(y1 * SCALE))
    const w = Math.min(width - left, Math.round((x2 - x1) * SCALE))
    const h = Math.min(height - top, Math.round((y2 - y1) * SCALE))
    if (w < 2 || h < 2) continue
    const region = await sharp(buf).extract({ left, top, width: w, height: h }).toBuffer()
    const small = await sharp(region).resize(Math.max(1, Math.round(w / CELL)), Math.max(1, Math.round(h / CELL)), { kernel: 'lanczos3' }).toBuffer()
    const blocky = await sharp(small).resize(w, h, { kernel: 'nearest' }).toBuffer()
    layers.push({ input: blocky, left, top })
  }
  return layers.length ? sharp(buf).composite(layers).toBuffer() : buf
}

for (const [id, shots] of Object.entries(SCREENSHOTS)) {
  const out = path.join(root, 'public/projects', id)
  fs.mkdirSync(out, { recursive: true })
  for (const f of fs.readdirSync(out)) if (f.endsWith('.webp')) fs.unlinkSync(path.join(out, f))
  result[id] = []
  for (const s of shots) {
    const src = path.join(root, 'assets/originals/projects', id, s.file)
    const meta = await sharp(src).metadata()
    const flat = await sharp(src).removeAlpha().png().toBuffer()
    const redacted = await pixelate(flat, s.redact ?? [], meta.width, meta.height)

    const main = await sharp(redacted).resize({ width: 2000, withoutEnlargement: true }).webp({ quality: 90, effort: 6 }).toFile(path.join(out, `${s.name}.webp`))
    // Square tile for the dome and mobile strip: top-left of the app so the sidebar and header stay recognizable.
    const side = Math.min(meta.width, meta.height)
    await sharp(redacted).extract({ left: 0, top: 0, width: side, height: side }).resize(720, 720).webp({ quality: 86, effort: 6 }).toFile(path.join(out, `${s.name}-tile.webp`))

    result[id].push({
      src: `/projects/${id}/${s.name}.webp`,
      tile: `/projects/${id}/${s.name}-tile.webp`,
      alt: s.alt,
      caption: s.caption,
      title: s.title,
      role: s.role,
      width: main.width,
      height: main.height,
      redacted: (s.redact ?? []).length > 0,
    })
    console.log(`${id}/${s.name}: ${main.width}x${main.height} ${(main.size / 1024).toFixed(0)}KB, ${(s.redact ?? []).length} regions pixelated`)
  }
}

fs.mkdirSync(path.join(root, 'public/logos'), { recursive: true })
const logos = {}
for (const l of LOGOS) {
  const src = path.join(root, 'assets/originals/logos', l.file)
  const info = await sharp(src).resize({ width: 256, height: 256, fit: 'inside', withoutEnlargement: true }).webp({ quality: 92, effort: 6 }).toFile(path.join(root, 'public/logos', `${l.name}.webp`))
  logos[l.name] = { src: `/logos/${l.name}.webp`, alt: l.alt, owner: l.owner, width: info.width, height: info.height }
  console.log(`logo ${l.name}: ${info.width}x${info.height} ${(info.size / 1024).toFixed(0)}KB`)
}

const body = `// GENERATED by scripts/prepare-project-images.mjs. Do not edit by hand.
// Real screenshots only (personal data pixelated). Projects with an empty list show labelled CONCEPT tiles.
export interface Screenshot {
  src: string
  tile: string
  alt: string
  caption: string
  title: string
  role: 'hero' | 'support' | 'detail'
  width: number
  height: number
  redacted: boolean
}

export interface Logo {
  src: string
  alt: string
  owner: string
  width: number
  height: number
}

export const screenshots: Record<'yamini' | 'kavya' | 'uzhavan', Screenshot[]> = ${JSON.stringify(result, null, 2)}

export const logos: Record<'yamini' | 'kavya' | 'uzhavan' | 'karunya' | 'lifechangersind', Logo> = ${JSON.stringify(logos, null, 2)}
`
fs.writeFileSync(path.join(root, 'src/data/screenshots.ts'), body)
console.log('wrote src/data/screenshots.ts')
